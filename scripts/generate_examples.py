def render(example: dict, model: str) -> str:
    """Run the example's turns in a fresh session and format the conversation."""
    context, thread = (
        Context(model=model, now=parse_now(example["now"])),
        uuid.uuid4().hex,
    )
    number = example["file"][:2].lstrip("0")
    lines = [
        f"# Example {number}: {example['title']}",
        "",
        f"{example['about']} `EMPORIO_NOW={example['now']}`, model `{model}`.",
        "Generated by `scripts/generate_examples.py`; not edited by hand.",
        "",
        "---",
        "",
        f"**CaduAI:** {prompts.GREETING}",
        "",
    ]
    for text in example["turns"]:
        added = run_turn(text, context, thread)
        calls = ", ".join(f"`{call}`" for call in tool_calls(added)) or "none"
        lines += [
            f"**Customer:** {text}",
            "",
            f"> Tools called: {calls}",
            "",
            f"**CaduAI:** {get_message_text(added[-1])}",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    load_dotenv(ROOT_DIR / ".env")
    model = Context().model
    error = config_error(model)
    if error:
        sys.exit(error)
    EXAMPLES_DIR.mkdir(exist_ok=True)
    for example in EXAMPLES:
        (EXAMPLES_DIR / example["file"]).write_text(
            render(example, model), encoding="utf-8"
        )
        print(f"Wrote examples/{example['file']}")


if __name__ == "__main__":
    main()
