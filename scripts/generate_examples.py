def render(example: dict, model: str) -> tuple[str, str]:
    """Run the example once in a fresh session; return it as Markdown and as a terminal SVG."""
    context, thread = (
        Context(model=model, now=parse_now(example["now"])),
        uuid.uuid4().hex,
    )
    number = example["file"][:2].lstrip("0")
    terminal = Console(record=True, width=100, file=io.StringIO())
    terminal.print(Text(prompts.CLI_HELP, style="dim"))
    cli.say(terminal, prompts.GREETING)
    lines = [
        f"# Example {number}: {example['title']}",
        "",
        f"{example['about']} `EMPORIO_NOW={example['now']}`, model `{model}`.",
        "Generated by `scripts/generate_examples.py`; not edited by hand.",
        "",
        f"![Terminal view of this conversation]({example['file'].removesuffix('.md')}.svg)",
        "",
        "---",
        "",
        f"**CaduAI:** {prompts.GREETING}",
        "",
    ]
    for text in example["turns"]:
        added = run_turn(text, context, thread)
        calls, reply = tool_calls(added), get_message_text(added[-1])
        terminal.print(Text.from_markup(cli.CUSTOMER_PROMPT) + Text(text))
        terminal.print(
            Text(f"tools called: {', '.join(calls) or 'none'}", style="dim italic")
        )
        cli.say(terminal, reply)
        listed = ", ".join(f"`{call}`" for call in calls) or "none"
        lines += [
            f"**Customer:** {text}",
            "",
            f"> Tools called: {listed}",
            "",
            f"**CaduAI:** {reply}",
            "",
        ]
    svg = terminal.export_svg(title=f"cadenza - example {number}")
    return "\n".join(lines).rstrip() + "\n", svg


def main() -> None:
    load_dotenv(ROOT_DIR / ".env")
    model = Context().model
    error = cli.config_error(model)
    if error:
        sys.exit(error)
    EXAMPLES_DIR.mkdir(exist_ok=True)
    selected = sys.argv[1:]
    for example in EXAMPLES:
        if selected and example["file"][:2] not in selected:
            continue
        markdown, svg = render(example, model)
        (EXAMPLES_DIR / example["file"]).write_text(markdown, encoding="utf-8")
        (EXAMPLES_DIR / example["file"].replace(".md", ".svg")).write_text(
            svg, encoding="utf-8"
        )
        print(f"Wrote examples/{example['file']} and its .svg")


if __name__ == "__main__":
    main()
