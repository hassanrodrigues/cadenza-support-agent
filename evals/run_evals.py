"""Run evals/cases.json against the agent once and write evals/results.md.

Usage: uv run python evals/run_evals.py   (needs the key for the provider in MODEL)
"""

from __future__ import annotations

import json
import re
import statistics
import sys
import time
import uuid
from dataclasses import dataclass
from datetime import date
from decimal import Decimal
from typing import Any

from dotenv import load_dotenv

from cadenza.cli import config_error
from cadenza.context import ROOT_DIR, Context, parse_now
from cadenza.graph import run_turn, token_usage, tool_calls
from cadenza.store_data import normalize_text
from cadenza.utils import get_message_text

CASES_PATH = ROOT_DIR / "evals" / "cases.json"
RESULTS_PATH = ROOT_DIR / "evals" / "results.md"
# Claude Haiku 5.5, prompts up to 100k tokens, USD per million tokens (Anthropic pricing page).
PRICE_PER_MTOK = {"input": Decimal("0.10"), "output": Decimal("0.50")}
AMOUNT = r"(\d{1,3}(?:\.\d{3})+|\d+)(?:,(\d{2}))?"
MONEY_RE = re.compile(rf"R\$\s*{AMOUNT}|{AMOUNT}\s*reais", re.IGNORECASE)


@dataclass
class Result:
    case: dict[str, Any]
    replies: list[str]
    tools: list[str]
    input_tokens: int
    output_tokens: int
    seconds: float
    failures: list[str]


def money_values(text: str) -> set[Decimal]:
    """Every BRL amount in the text: "R$2199", "R$ 2.199,00" and "2199 reais" are equal."""
    values = set()
    for match in MONEY_RE.finditer(text):
        whole, cents = (match[1], match[2]) if match[1] else (match[3], match[4])
        values.add(Decimal(f"{whole.replace('.', '')}.{cents or '00'}"))
    return values


def matches(fact: Any, text: str) -> bool:
    """A fact is a text snippet, {"money": "2199.00"}, or a list meaning any of them."""
    if isinstance(fact, list):
        return any(matches(item, text) for item in fact)
    if isinstance(fact, dict):
        return Decimal(fact["money"]) in money_values(text)
    return normalize_text(fact) in normalize_text(text)


def check(case: dict[str, Any], replies: list[str], tools: list[str]) -> list[str]:
    """Failures of one case: expected tool, facts in the last reply, nothing forbidden anywhere."""
    failures = []
    expected = case.get("expected_tools", [])
    called = {t.split("(")[0] for t in tools}
    if expected and not called & set(expected):
        failures.append(f"expected a call to {' or '.join(expected)}")
    for fact in case.get("expected_facts", []):
        if not matches(fact, replies[-1]):
            failures.append(f"missing {json.dumps(fact, ensure_ascii=False)}")
    for fact in case.get("forbidden", []):
        if matches(fact, "\n".join(replies)):
            failures.append(f"forbidden {json.dumps(fact, ensure_ascii=False)}")
    return failures


def run_case(case: dict[str, Any]) -> Result:
    """Play every turn of a case in a fresh thread with the case's fixed reference time."""
    context, thread = Context(now=parse_now(case["now"])), uuid.uuid4().hex
    replies, tools, tokens_in, tokens_out = [], [], 0, 0
    start = time.perf_counter()
    for text in case["turns"]:
        added = run_turn(text, context, thread)
        replies.append(get_message_text(added[-1]))
        tools += tool_calls(added)
        used_in, used_out = token_usage(added)
        tokens_in, tokens_out = tokens_in + used_in, tokens_out + used_out
    seconds = time.perf_counter() - start
    return Result(
        case,
        replies,
        tools,
        tokens_in,
        tokens_out,
        seconds,
        check(case, replies, tools),
    )


def cost(results: list[Result]) -> Decimal:
    tokens_in = sum(r.input_tokens for r in results)
    tokens_out = sum(r.output_tokens for r in results)
    total = tokens_in * PRICE_PER_MTOK["input"] + tokens_out * PRICE_PER_MTOK["output"]
    return total / 1_000_000


def report(results: list[Result], model: str) -> str:
    """Markdown report: summary, one row per case, failures, then every conversation."""
    suites = ("functional", "adversarial")
    passed = {s: [r for r in results if r.case["suite"] == s] for s in suites}
    lines = [
        "# Eval results",
        "",
        f"Generated by `evals/run_evals.py` on {date.today():%Y-%m-%d} with `{model}`: one run of "
        f"{len(results)} cases from `evals/cases.json`. Not edited by hand.",
        "",
        "| Suite | Passed |",
        "|---|---|",
        *(
            f"| {s.title()} | {sum(not r.failures for r in passed[s])}/{len(passed[s])} |"
            for s in suites
        ),
        "",
        f"Tokens: {sum(r.input_tokens for r in results):,} input, "
        f"{sum(r.output_tokens for r in results):,} output (output includes thinking). "
        f"Estimated cost: US$ {cost(results):.4f} at Claude Haiku 5.5 prices "
        f"(US$ {PRICE_PER_MTOK['input']} / {PRICE_PER_MTOK['output']} per million input/output tokens). "
        f"Median time per case: {statistics.median(r.seconds for r in results):.1f} s.",
        "",
        "| Case | Title | Result | Tools called | Tokens in/out | Seconds |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        verdict = "pass" if not r.failures else "**fail**"
        tools = "<br>".join(f"`{t}`" for t in r.tools) or "none"
        lines.append(
            f"| {r.case['id']} | {r.case['title']} | {verdict} | {tools} | "
            f"{r.input_tokens:,}/{r.output_tokens:,} | {r.seconds:.1f} |"
        )
    failed = [r for r in results if r.failures]
    lines += ["", "## Failures", "", "None." if not failed else ""]
    for r in failed:
        lines += [f"### {r.case['id']}: {r.case['title']}", ""]
        lines += [f"- {failure}" for failure in r.failures]
        lines += [
            "",
            "Last reply:",
            "",
            *(f"> {line}" for line in r.replies[-1].splitlines()),
            "",
        ]
    lines += ["## Conversations", ""]
    for r in results:
        verdict = "pass" if not r.failures else "fail"
        lines += [
            f"<details><summary>{r.case['id']}: {r.case['title']} ({verdict})</summary>",
            "",
        ]
        for text, reply in zip(r.case["turns"], r.replies):
            lines += [f"**Customer:** {text}", "", f"**CaduAI:** {reply}", ""]
        lines += ["</details>", ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    load_dotenv(ROOT_DIR / ".env")
    model = Context().model
    error = config_error(model)
    if error:
        sys.exit(error)
    results = []
    for case in json.loads(CASES_PATH.read_text(encoding="utf-8")):
        result = run_case(case)
        print(
            f"{case['id']} {'pass' if not result.failures else 'FAIL'} {result.failures}"
        )
        results.append(result)
    RESULTS_PATH.write_text(report(results, model), encoding="utf-8")
    print(
        f"Wrote {RESULTS_PATH.relative_to(ROOT_DIR)}; estimated cost US$ {cost(results):.4f}"
    )


if __name__ == "__main__":
    main()
